"""Abstract Provider-Neutral Agent Adapter Interface for Hey Jev.

Every agent provider (Antigravity, local models, cloud LLMs, PC automation)
must implement this interface to be integrated into Jev's orchestrator.
"""
from __future__ import annotations

from abc import ABC, abstractmethod
from typing import Any, Dict, Iterator, List, Optional

from agent_task import AgentTask, TaskStatus
from agent_result import AgentResult


class AgentAdapter(ABC):
    """Abstract interface defining required and optional provider capabilities."""

    @abstractmethod
    def submit_task(self, task: AgentTask) -> bool:
        """Submit an AgentTask to this provider for execution.
        
        Returns True if accepted, False otherwise.
        """
        pass

    @abstractmethod
    def get_task_status(self, task_id: str) -> TaskStatus:
        """Query the current lifecycle status of a submitted task."""
        pass

    @abstractmethod
    def stream_agent_output(self, task_id: str) -> Iterator[str]:
        """Stream real-time text output / logs generated by this task."""
        pass

    @abstractmethod
    def cancel_task(self, task_id: str, reason: str = "") -> bool:
        """Request cancellation of an active task.
        
        Returns True if cancellation request was received and accepted.
        """
        pass

    @abstractmethod
    def get_task_result(self, task_id: str) -> Optional[AgentResult]:
        """Retrieve the normalized AgentResult once the task is finished."""
        pass

    @abstractmethod
    def approve_action(self, task_id: str, action_id: str, approved: bool) -> bool:
        """Approve or reject a pending action requiring human approval."""
        pass

    # Optional extension methods
    def health_check(self) -> Dict[str, Any]:
        """Perform a quick provider health check.
        
        Returns a dict e.g. {"status": "healthy", "latency_ms": 12}.
        """
        return {"status": "healthy", "provider": self.__class__.__name__}

    def capabilities(self) -> List[str]:
        """Return list of capability strings supported by this adapter."""
        return []

    def discover(self) -> Dict[str, Any]:
        """Discover available local models, environments, or tool hooks."""
        return {
            "name": self.__class__.__name__,
            "capabilities": self.capabilities(),
        }

    def pause_task(self, task_id: str) -> bool:
        """Pause execution of a task if supported."""
        return False

    def resume_task(self, task_id: str) -> bool:
        """Resume execution of a paused task if supported."""
        return False
